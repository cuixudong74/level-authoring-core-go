// Package levelcore 提供一个纯进程内、无外部依赖的关卡/地图编辑内核。
//
// 核心能力
//
//   - 编辑以命令（Command）表达，每条命令既可应用也可撤销；
//   - 多条命令可作为一个批次原子提交，失败时整体不生效；
//   - 连续同类微调（同格刷地形、连续拖拽实体）按时间窗合并为一条历史；
//   - 文档受一组一致性约束保护，违例编辑被拒绝并给出可区分的错误码；
//   - 派生产物（Artifact）支持增量重建，且与从零全量重建逐字段一致；
//   - 文档与产物可确定性地打包为带格式版本与校验和的二进制产物；
//   - 旧版本/损坏输入被安全识别并返回类型化错误，绝不崩溃；
//   - 单次编辑成本只与改动量相关，不随文档总规模线性增长。
//
// 确定性
//
// 内核不读取本机墙钟或随机源：合并窗口所需的时间戳由提交方随命令提供。
// 同一份初始文档与同一串命令（含相同时间戳）在任意机器上产生
// 逐字段一致的文档、历史记录与打包字节。派生遍历均使用固定顺序
// （图层顺序、ID 排序、块的行列序、单元下标序）。
//
// 典型用法
//
//	ed, err := levelcore.NewEditor(doc, levelcore.DefaultConfig())
//	res, err := ed.Submit(levelcore.NewSetTileCommand("ground",
//	    levelcore.Point{X: 1, Y: 1}, 7, ts))
//	ed.Undo()
//	ed.Redo()
//	pkg, err := levelcore.Pack(ed.Document(), ed.Artifact())
//
// 详见 README.md 中的命令语义、约束规则与产物格式说明。
